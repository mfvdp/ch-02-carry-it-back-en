    // Restart marker for the restart after the game has ended. The end screen sets it right before control.reset(). The
    // next start reads it, deletes it at once and then goes straight to the title image, without the intro. After the
    // game has been switched off and on, the marker is gone, so the intro plays again.
    export const restartMarker = "neustart-titel"
    // True when this start is a restart after the game has ended.
    export let directToTitle = false
    export function text(textId: TextId): string {
        return strings[textId]
    }
    export function format(textId: TextId, first: number, second: number = 0): string {
        let s = text(textId)
        let i = s.indexOf("{0}")
        if (i >= 0) s = s.substr(0, i) + first + s.substr(i + 3)
        i = s.indexOf("{1}")
        if (i >= 0) s = s.substr(0, i) + second + s.substr(i + 3)
        return s
    }
    // At the start: if the restartMarker is set, the game goes straight to the title image. The marker only counts for
    // this one start and is deleted at once. After that the menus are added.
    export function initialize(): void {
        directToTitle = settings.exists(restartMarker)
        if (directToTitle) settings.remove(restartMarker)
        pause(100)
        installMenus()
    }
